// build-single.cjs — the whole editor in one HTML file: editor/dist/instructbase-editor.html
//
//   node editor/build-single.cjs
//
// Inlines editor.css, every script and both new-lesson templates into editor/index.html.
// The output is generated: edit the sources and rebuild. A model test fails when the
// committed file differs from a fresh build.
// Not included: the service worker and the manifest (a single file cannot carry a service
// worker, so this build is not installable; it runs from file:// with no network).
'use strict';
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const OUT = path.join(DIR, 'dist', 'instructbase-editor.html');
const read = (rel) => fs.readFileSync(path.join(DIR, rel), 'utf8');

function once(src, find, make) {
  const i = src.indexOf(find);
  if (i < 0 || src.indexOf(find, i + 1) >= 0) throw new Error('expected exactly one: ' + find);
  return src.slice(0, i) + make() + src.slice(i + find.length);   // a function, so "$" in the payload is literal
}
/* inline script text: "</script" would end the element, and "<!--" puts the HTML
   parser into the escaped state; in JavaScript "<\/" and "<\!" mean the same characters */
function inlineJs(code) { return code.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--'); }

function build() {
  let html = read('index.html');
  html = once(html, '<!doctype html>', () => '<!doctype html>\n<!-- Generated by editor/build-single.cjs from editor/. Do not edit this file; edit the sources and rebuild. -->');
  html = once(html, '<link rel="manifest" href="manifest.webmanifest">\n', () => '');
  const icon = 'data:image/svg+xml;base64,' + Buffer.from(read('icons/icon.svg')).toString('base64');
  html = once(html, '<link rel="icon" href="icons/icon.svg" type="image/svg+xml">', () => '<link rel="icon" href="' + icon + '" type="image/svg+xml">');
  html = once(html, '<link rel="stylesheet" href="css/editor.css">', () => '<style>\n' + read('css/editor.css') + '</style>');
  const templates = {
    'editor/templates/deck-template.html': read('templates/deck-template.html'),
    'editor/templates/guide-template.html': read('templates/guide-template.html')
  };
  const scripts = [...html.matchAll(/<script src="js\/([\w.-]+)"><\/script>/g)].map((m) => m[1]);
  if (!scripts.length) throw new Error('no scripts found in index.html');
  scripts.forEach((name, i) => {
    html = once(html, '<script src="js/' + name + '"></script>', () =>
      (i === 0 ? '<script>window.IB_SINGLE = true;</script>\n<script type="application/json" id="ib-templates">' +
        JSON.stringify(templates).replace(/</g, '\\u003c') + '</script>\n' : '') +
      '<script>\n' + inlineJs(read('js/' + name)) + '</script>');
  });
  if (/\s(src|href)="(?!data:|#)[^"]*"/.test(html.replace(/<script type="application\/json"[\s\S]*?<\/script>/, '').replace(/<script>[\s\S]*?<\/script>/g, '').replace(/<style>[\s\S]*?<\/style>/g, ''))) {
    throw new Error('the page still references an external file');
  }
  return html;
}

if (require.main === module) {
  const html = build();
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, html);
  console.log(path.relative(process.cwd(), OUT) + ' · ' + Math.round(html.length / 1024) + ' KB');
}
module.exports = { build, OUT };
